#!/usr/bin/env node
/**
 * V7 Serve Generator
 * Generates a standalone Node.js server for serving extracted webapp offline
 *
 * Features:
 * - URL lookup table mapping original URLs to local files
 * - CORS headers for cross-origin requests
 * - SPA fallback to index.html
 * - MIME type detection
 * - Pure offline mode (404 for missing, no proxy)
 * - Logs missing resources for gap identification
 */

import fs from 'fs';
import path from 'path';

/**
 * Generate serve.js content for an extraction
 * @param {Object} options
 * @param {string} options.outputDir - Path to extraction output directory
 * @param {Object} options.manifest - Manifest object with resources array
 * @param {number} options.port - Server port (default 3333)
 * @returns {string} - serve.js file content
 */
export function generateServeJs(options) {
  const { manifest, port = 3333 } = options;

  // Build URL to local file mapping
  const urlMap = {};
  for (const resource of (manifest.resources || [])) {
    if (resource.url && resource.localPath) {
      urlMap[resource.url] = resource.localPath;

      // Also map by pathname only
      try {
        const urlObj = new URL(resource.url);
        urlMap[urlObj.pathname] = resource.localPath;

        // Strip query params too
        const pathNoQuery = urlObj.pathname.split('?')[0];
        if (pathNoQuery !== urlObj.pathname) {
          urlMap[pathNoQuery] = resource.localPath;
        }
      } catch (e) {
        // Invalid URL, skip pathname mapping
      }
    }
  }

  const serveJs = `#!/usr/bin/env node
/**
 * Offline Server for ${manifest.url || 'extracted webapp'}
 * Generated by V7 Extract - Pure offline mode
 *
 * Usage: node serve.js [port]
 * Default port: ${port}
 */

const http = require('http');
const fs = require('fs');
const path = require('path');

const PORT = process.argv[2] || ${port};
const DIR = __dirname;

// MIME types
const MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.mjs': 'application/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.wasm': 'application/wasm',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.webp': 'image/webp',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.ttf': 'font/ttf',
  '.otf': 'font/otf',
  '.eot': 'application/vnd.ms-fontobject',
  '.mp3': 'audio/mpeg',
  '.mp4': 'video/mp4',
  '.webm': 'video/webm',
  '.zip': 'application/zip',
  '.pdf': 'application/pdf',
  '.xml': 'application/xml',
  '.txt': 'text/plain; charset=utf-8',
  '.map': 'application/json',
};

// URL to local file mapping (generated from manifest)
const URL_MAP = ${JSON.stringify(urlMap, null, 2)};

// Track missing resources for debugging
const missingResources = new Set();

function getMimeType(filePath) {
  const ext = path.extname(filePath).toLowerCase();
  return MIME_TYPES[ext] || 'application/octet-stream';
}

function serveFile(filePath, res) {
  fs.readFile(filePath, (err, data) => {
    if (err) {
      res.writeHead(404, { 'Content-Type': 'text/plain' });
      res.end('Not found: ' + filePath);
      return;
    }

    res.writeHead(200, {
      'Content-Type': getMimeType(filePath),
      'Access-Control-Allow-Origin': '*',
      'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
      'Access-Control-Allow-Headers': '*',
      'Cache-Control': 'no-cache',
    });
    res.end(data);
  });
}

const server = http.createServer((req, res) => {
  // Handle CORS preflight
  if (req.method === 'OPTIONS') {
    res.writeHead(204, {
      'Access-Control-Allow-Origin': '*',
      'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
      'Access-Control-Allow-Headers': '*',
    });
    res.end();
    return;
  }

  const reqPath = req.url.split('?')[0];

  // Root or index.html
  if (reqPath === '/' || reqPath === '/index.html') {
    serveFile(path.join(DIR, 'index.html'), res);
    return;
  }

  // Check URL map (full URL or pathname)
  const mappedPath = URL_MAP[req.url] || URL_MAP[reqPath];
  if (mappedPath) {
    const filePath = path.join(DIR, mappedPath);
    if (fs.existsSync(filePath)) {
      console.log('[HIT]', reqPath, '->', mappedPath);
      serveFile(filePath, res);
      return;
    }
  }

  // Try direct file path in resources/
  const directPath = path.join(DIR, 'resources', reqPath);
  if (fs.existsSync(directPath)) {
    console.log('[DIR]', reqPath);
    serveFile(directPath, res);
    return;
  }

  // Try without leading slash
  const noSlashPath = path.join(DIR, 'resources', reqPath.replace(/^\\//, ''));
  if (fs.existsSync(noSlashPath)) {
    console.log('[DIR]', reqPath);
    serveFile(noSlashPath, res);
    return;
  }

  // SPA fallback - serve index.html for HTML requests
  const acceptHeader = req.headers.accept || '';
  if (acceptHeader.includes('text/html') && !reqPath.includes('.')) {
    console.log('[SPA]', reqPath, '-> index.html');
    serveFile(path.join(DIR, 'index.html'), res);
    return;
  }

  // 404 - log missing resource
  if (!missingResources.has(reqPath)) {
    missingResources.add(reqPath);
    console.log('[MISS]', reqPath);
  }

  res.writeHead(404, {
    'Content-Type': 'text/plain',
    'Access-Control-Allow-Origin': '*',
  });
  res.end('Not found (offline): ' + reqPath);
});

server.listen(PORT, () => {
  console.log('');
  console.log('='.repeat(50));
  console.log('  Offline Server Running');
  console.log('='.repeat(50));
  console.log('  URL: http://localhost:' + PORT);
  console.log('  Mode: Pure offline (no proxy fallback)');
  console.log('  Resources mapped: ' + Object.keys(URL_MAP).length);
  console.log('='.repeat(50));
  console.log('');
  console.log('Logs:');
  console.log('  [HIT]  - Served from URL map');
  console.log('  [DIR]  - Served from resources/');
  console.log('  [SPA]  - SPA fallback to index.html');
  console.log('  [MISS] - Resource not found (404)');
  console.log('');
});

// Log summary on exit
process.on('SIGINT', () => {
  console.log('');
  console.log('Missing resources (' + missingResources.size + '):');
  for (const r of [...missingResources].slice(0, 20)) {
    console.log('  ' + r);
  }
  if (missingResources.size > 20) {
    console.log('  ... and ' + (missingResources.size - 20) + ' more');
  }
  process.exit(0);
});
`;

  return serveJs;
}

/**
 * Write serve.js to extraction directory
 * @param {string} outputDir - Extraction output directory
 * @param {Object} manifest - Manifest object
 * @param {number} port - Server port
 */
export async function writeServeJs(outputDir, manifest, port = 3333) {
  const content = generateServeJs({ manifest, port });
  const servePath = path.join(outputDir, 'serve.js');

  await fs.promises.writeFile(servePath, content);
  await fs.promises.chmod(servePath, 0o755);

  console.log(`[serve-generator] Created ${servePath}`);
  return servePath;
}

// CLI usage
if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);

  if (args.length < 1) {
    console.log('Usage: node serve-generator.js <output-dir> [port]');
    console.log('');
    console.log('Generates serve.js in the output directory based on manifest.json');
    process.exit(1);
  }

  const outputDir = args[0];
  const port = parseInt(args[1]) || 3333;

  const manifestPath = path.join(outputDir, 'manifest.json');
  if (!fs.existsSync(manifestPath)) {
    console.error('Error: manifest.json not found in', outputDir);
    process.exit(1);
  }

  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf-8'));
  writeServeJs(outputDir, manifest, port)
    .then(() => console.log('Done!'))
    .catch(err => {
      console.error('Error:', err);
      process.exit(1);
    });
}
